import os
import sys
from nbconvert import MarkdownExporter
from nbformat import read
from glob import glob
from logger import Logger
from preprocess import (
    StripANSICodesPreprocessor,
    HideWidgetOutputPreprocessor,
    HideLongPipInstallOutputPreprocessor,
)

# Paths are anchored to this script's location, so the converter scans the
# cookbook and writes to util/convert/output_md/ no matter which working
# directory it is launched from (previously it scanned "<cwd>/../../").
script_dir = os.path.dirname(os.path.abspath(__file__))
project_dir = os.path.normpath(os.path.join(script_dir, "..", ".."))
markdown_dir = os.path.join(script_dir, "output_md")
base_github_url = "https://github.com/couchbase-examples/mcp-cookbook/tree/main"

# Autogenerated markdown warning comment
autogenerated_md_warning = "<!--- *** WARNING ***: Autogenerated markdown file from jupyter notebook. ***DO NOT EDIT THIS FILE***. Changes should be made to the original notebook file. See commit message for source repo. -->"


def build_exporter():
    """Return nbconvert's Markdown exporter with the cookbook's preprocessors."""
    exporter = MarkdownExporter()
    exporter.register_preprocessor(StripANSICodesPreprocessor, enabled=True)
    exporter.register_preprocessor(HideWidgetOutputPreprocessor, enabled=True)
    exporter.register_preprocessor(HideLongPipInstallOutputPreprocessor, enabled=True)
    return exporter


def output_name(relative_path):
    """Map 'dir/sub/Notebook.ipynb' to 'dir-sub-Notebook.md'."""
    notebook_name = os.path.splitext(os.path.basename(relative_path))[0]
    dir_name = os.path.dirname(relative_path).replace(os.sep, "-")
    return f"{dir_name}-{notebook_name}.md" if dir_name else f"{notebook_name}.md"


def convert_notebook(notebook_path, exporter, root=project_dir):
    """Convert one notebook to tutorial markdown.

    Returns (output_file_name, markdown), or None when the notebook has no
    sibling frontmatter.md and must not be published.
    """
    frontmatter_path = os.path.join(os.path.dirname(notebook_path), "frontmatter.md")
    if not os.path.isfile(frontmatter_path):
        return None

    with open(frontmatter_path, "r", encoding="utf-8") as frontmatter_file:
        frontmatter_content = frontmatter_file.read()

    with open(notebook_path, "r", encoding="utf-8") as f:
        notebook = read(f, as_version=4)

    # Relative path builds both the 'View Source' GitHub URL and the output name
    relative_path = os.path.relpath(notebook_path, root)
    view_source_link = f"[View Source]({base_github_url}/{relative_path})"

    body, _ = exporter.from_notebook_node(notebook)

    combined_markdown = f"{frontmatter_content}\n\n{autogenerated_md_warning}\n\n\n{view_source_link}\n\n{body}"
    return output_name(relative_path), combined_markdown


def main(root=project_dir, out_dir=markdown_dir):
    os.makedirs(out_dir, exist_ok=True)
    exporter = build_exporter()

    for notebook_path in sorted(
        glob(os.path.join(root, "**", "*.ipynb"), recursive=True)
    ):
        result = convert_notebook(notebook_path, exporter, root)
        if result is None:
            Logger.fail_conversion(notebook_path, "frontmatter.md not found")
            continue

        file_name, combined_markdown = result
        markdown_file = os.path.join(out_dir, file_name)
        with open(markdown_file, "w", encoding="utf-8") as f:
            f.write(combined_markdown)

        Logger.success_conversion(notebook_path, markdown_file, "with frontmatter")


if __name__ == "__main__":
    sys.exit(main())
